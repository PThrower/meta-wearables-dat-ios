// --- FRLY frame builder (for WS mock) ---

const FRLY_MAGIC = [0x46, 0x52, 0x4c, 0x59];
const FRAU_MAGIC = [0x46, 0x52, 0x41, 0x55];

export function buildFRLYFrame(seq: number, width: number, height: number, jpeg: Uint8Array): ArrayBuffer {
  const headerSize = 29;
  const buf = new ArrayBuffer(headerSize + jpeg.length);
  const view = new DataView(buf);
  const arr = new Uint8Array(buf);

  arr[0] = FRLY_MAGIC[0]; arr[1] = FRLY_MAGIC[1]; arr[2] = FRLY_MAGIC[2]; arr[3] = FRLY_MAGIC[3];
  view.setBigUint64(4, BigInt(seq), true);
  view.setUint32(12, width, true);
  view.setUint32(16, height, true);
  view.setUint8(20, 80); // quality
  view.setBigUint64(21, BigInt(Date.now()), true);
  arr.set(jpeg, headerSize);

  return buf;
}

export function buildFRAUFrame(seq: number, sampleRate: number, channels: number, pcmInt16: Int16Array): ArrayBuffer {
  const headerSize = 29;
  const buf = new ArrayBuffer(headerSize + pcmInt16.byteLength);
  const view = new DataView(buf);
  const arr = new Uint8Array(buf);

  arr[0] = FRAU_MAGIC[0]; arr[1] = FRAU_MAGIC[1]; arr[2] = FRAU_MAGIC[2]; arr[3] = FRAU_MAGIC[3];
  view.setUint8(4, 0); // codecType
  view.setBigUint64(5, BigInt(seq), true);
  view.setUint32(13, sampleRate, true);
  view.setUint16(17, channels, true);
  view.setUint16(19, 16, true); // bitsPerSample
  view.setBigUint64(21, BigInt(Date.now()), true);
  arr.set(new Uint8Array(pcmInt16.buffer, pcmInt16.byteOffset, pcmInt16.byteLength), headerSize);

  return buf;
}

